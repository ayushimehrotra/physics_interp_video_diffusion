"""Probe `energy_voe_v1`: impossible (energy created) vs legal (energy lost), matched twins.

WHAT THIS MEASURES, AND WHAT IT DOES NOT. §46c says it plainly and it bears repeating
at the top of the script that produces the number: `e` is mass-free and visible, so a
probe separates the two classes by reading how fast the balls separate. Expect an AUC
near 1.000 and do NOT read it as evidence of an energy concept -- §44 established that
the whole family of such numbers is accounted for by relative speed. The mass-free
ceiling is printed next to every result for exactly this reason.

What the number IS good for: confirming the captures are sound, confirming the classes
are rendered as designed, and giving the VoE analysis a reference point for how legible
the manipulation is at all.

THE PAIRED READOUT is the part worth having. Every seed carries three clips that share
a bit-identical pre-contact segment -- `anchor` (e=1), `impossible` (e=k) and `legal`
(e=1/k) -- so the comparison can be made WITHIN a seed and all between-scene variance
drops out. `impossible` and `legal` sit the same distance from elastic in log space, so
a probe that ranks them apart is reading the SIGN of the deviation, not its size.

Folds are grouped by seed throughout: the three twins of a seed share everything up to
contact, so splitting by clip would let the probe memorise a scene and recognise its
siblings (§42b measured that trap at 0.787 discrimination on leak-free data).

    .venv/bin/python scripts/kinetic_energy/probe_energy_voe.py \
        --outputs outputs/evoe_videomae-base outputs/evoe_vjepa2-vitl
"""
