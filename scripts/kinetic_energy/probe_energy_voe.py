def paired_permuted_labels(y: np.ndarray, groups: np.ndarray, n_perm: int,
                           seed: int) -> np.ndarray:
    """`[n, n_perm+1]`; column 0 is observed. THE EXACT PAIRED NULL.

    `probe_energy.permuted_labels` permutes whole GROUPS, and on this set that is a
    NO-OP: every seed contributes exactly one `impossible` and one `legal` clip in the
    same order, so the label pattern is identical in every group and permuting groups
    reproduces the observed vector bit for bit. Measured: 20/20 draws identical, which
    surfaced as every p-value reading 1.000 and the max-over-grid null p95 sitting
    exactly on the observed AUC.

    Under H0 the two twins of a pair are exchangeable, so the null is generated by
    flipping WHICH TWIN carries the label, independently per pair with probability 1/2.
    That is exact rather than asymptotic and it is the same construction
    `probe_conservation_set.py` uses for its matched twins.
    """
    rng = np.random.default_rng(seed)
    slots = [np.flatnonzero(groups == g) for g in np.unique(groups)]
    cols = [y.astype(float)]
    for _ in range(n_perm):
        z = y.astype(float).copy()
        for s in slots:
            if len(s) == 2 and rng.random() < 0.5:
                z[s] = z[s][::-1]
        cols.append(z)
    return np.stack(cols, axis=1)


def load(outdir: str):
    paths = sorted(glob.glob(f"{outdir}/momentum_probe/activations/*.npz"))
    if not paths:
        raise FileNotFoundError(f"no captures in {outdir}")
    store, labels, pools, sites = {}, [], None, None
    for p in paths:
        z = np.load(p, allow_pickle=True)
        m = json.loads(bytes(z["meta"]).decode())
        pools = m["pools"]
        labels.append(m["labels"])
        sites = sites or [k[4:] for k in z.files if k.startswith("act.")]
        for s in sites:
            store.setdefault(s, []).append(z["act." + s][0])
    return {s: np.stack(v).astype(np.float32) for s, v in store.items()}, labels, pools


def facts(L: dict) -> dict:
    c = L["collision"]
    e_t = L["energy_edit"]["e_target"]
    vA = np.array(c["pre"]["velocity_A"][:2], float)
    vB = np.array(c["pre"]["velocity_B"][:2], float)
    dvA = np.array(c["post"]["velocity_A"][:2], float) - vA
    n = dvA / max(np.linalg.norm(dvA), 1e-12)
    return dict(seed=L["seed"], e_target=e_t,
                cell=("impossible" if e_t > 1 else "anchor" if e_t == 1 else "legal"),
                kr=c["kinetic_energy_ratio"],
                e_meas=c["restitution_measured"],
                mom_err=c["momentum_rel_error"],
                rel_post=float(np.linalg.norm(
                    np.array(c["post"]["velocity_A"][:2], float)
                    - np.array(c["post"]["velocity_B"][:2], float))),
                speed_sum_post=float(np.linalg.norm(c["post"]["velocity_A"][:2])
                                     + np.linalg.norm(c["post"]["velocity_B"][:2])))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--outputs", nargs="+", required=True)
    ap.add_argument("--n-perm", type=int, default=200)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("-o", "--out", default="docs/artifacts/energy_voe_probes.json")
    args = ap.parse_args()

    report: dict = {"pools": POOLS}
    for outdir in args.outputs:
        acts, labels, pools = load(outdir)
        F = [facts(L) for L in labels]
        cells = {f"{s}/{p}": acts[s][:, pools.index(p), :] for s in acts for p in POOLS}
        cellnames = list(cells)
        seeds = np.array([f["seed"] for f in F])
        cellv = np.array([f["cell"] for f in F])
        print(f"\n{'=' * 86}\n{outdir}   {len(F)} clips, {len(cells)} cells")

        # sanity: the set must be what it claims before any probe is read
        mom = np.array([f["mom_err"] for f in F])
        kr = np.array([f["kr"] for f in F])
        print(f"  momentum rel error   max {mom.max():.2e}   "
              f"{'OK' if mom.max() < 1e-9 else 'FAIL — do not read further'}")
        for cell in ("anchor", "legal", "impossible"):
            m = cellv == cell
            if m.any():
                print(f"    {cell:11s} n={int(m.sum()):3d}  KE ratio "
                      f"[{kr[m].min():.3f}, {kr[m].max():.3f}]  "
                      f"created {int((kr[m] > 1 + 1e-9).sum())}/{int(m.sum())}")

        sel = cellv != "anchor"
        y = (cellv[sel] == "impossible")
        g = seeds[sel]
        Ys = paired_permuted_labels(y, g, args.n_perm, args.seed)

        # the ceiling, as always
        orc = {}
        for name in ("e_meas", "rel_post", "speed_sum_post"):
            v = np.array([f[name] for f in F])[sel]
            a = auc(y, v)
            orc[name] = max(a, 1 - a)
        mf = max(orc.values())
        print(f"\n  --- impossible vs legal   n={int(sel.sum())}  "
              f"({int(y.sum())} impossible / {int((~y).sum())} legal), grouped by seed")
        print("      mass-free oracles: " + "  ".join(f"{k} {v:.3f}" for k, v in orc.items()))
        print(f"      >>> MASS-FREE CEILING {mf:.3f} — a probe at or below this has "
              f"read separation speed (§44) <<<")

        grid = {}
        for cname, X in cells.items():
            oof = cell_oof_scores(X[sel], Ys, g, args.seed)
            grid[cname] = auc_cols(np.repeat(y[:, None], Ys.shape[1], axis=1), oof)
        A = np.stack([grid[c] for c in cellnames])
        obs, null = A[:, 0], A[:, 1:]
        nullmax = null.max(axis=0)
        b = int(np.argmax(obs))
        p_corr = float((nullmax >= obs[b]).mean())

        print("      per-pool best over sites (AUC, uncorrected p):")
        per_pool = {}
        for p in POOLS:
            idxs = [i for i, c in enumerate(cellnames) if c.endswith("/" + p)]
            j = idxs[int(np.argmax(obs[idxs]))]
            pv = float((null[j] >= obs[j]).mean())
            per_pool[p] = {"cell": cellnames[j], "auc": float(obs[j]), "p": pv}
            print(f"        {p:9s} {obs[j]:.3f}  p={pv:.3f}   {cellnames[j].split('/')[0]}")
        print(f"      GRID BEST {obs[b]:.3f} at {cellnames[b]}   "
              f"max-over-grid null p95 {np.percentile(nullmax, 95):.3f}  "
              f"p_corrected = {p_corr:.3f}")

        # ---- the paired readout, which is what the twins were rendered for --------
        pairs = []
        for s in np.unique(seeds):
            i = np.flatnonzero((seeds == s) & (cellv == "impossible"))
            j = np.flatnonzero((seeds == s) & (cellv == "legal"))
            if len(i) == 1 and len(j) == 1:
                pairs.append((int(i[0]), int(j[0])))
        print(f"\n      PAIRED within seed ({len(pairs)} twin pairs): fraction of pairs whose")
        print("      IMPOSSIBLE twin outscores its own LEGAL twin —")
        Yfull = np.zeros((len(F), 1))
        Yfull[[i for i, _ in pairs], 0] = 1.0
        idx = np.array([k for pr in pairs for k in pr])
        yb = np.array([True, False] * len(pairs))
        gb = np.array([s for s in np.unique(seeds) for _ in range(2)][:len(idx)])
        Yb = paired_permuted_labels(yb, gb, args.n_perm, args.seed)
        wins_all = {}
        for cname, X in cells.items():
            oof = cell_oof_scores(X[idx], Yb, gb, args.seed)
            w = np.array([[oof[2 * t, c] > oof[2 * t + 1, c] for t in range(len(pairs))]
                          for c in range(Yb.shape[1])]).mean(axis=1)
            # column 0 is observed; the rest are the exact paired null
            wins_all[cname] = w
        W = np.stack([wins_all[c] for c in cellnames])
        obs_w, null_w = W[:, 0], W[:, 1:]
        nm = null_w.max(axis=0)
        bw = int(np.argmax(obs_w))
        p_w = float((nm >= obs_w[bw]).mean())
        best_pair, best_name = float(obs_w[bw]), cellnames[bw]
        print(f"        best cell {best_pair:.3f}   {best_name}   (0.5 = chance)")
        print(f"        max-over-grid paired null: mean {nm.mean():.3f}  "
              f"95th {np.percentile(nm, 95):.3f}   p_corrected = {p_w:.3f}")

        report[outdir] = {"n": len(F), "mass_free_ceiling": mf, "oracles": orc,
                          "per_pool": per_pool,
                          "grid_best": {"cell": cellnames[b], "auc": float(obs[b]),
                                        "p_corrected": p_corr},
                          "paired_best": {"cell": best_name, "fraction": best_pair,
                                          "n_pairs": len(pairs), "p_corrected": p_w,
                                          "null_max_p95": float(np.percentile(nm, 95))},
                          "max_momentum_rel_error": float(mom.max())}

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    json.dump(report, open(args.out, "w"), indent=1)
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
